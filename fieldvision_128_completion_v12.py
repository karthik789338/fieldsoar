#!/usr/bin/env python3
"""128-UAV completion campaign for FieldVision H1/H2/H3.

Keeps v8, v9 and v10 source-hashed runners untouched. Reuses existing full,
IPPO and QMIX evaluations. Adds missing 7 MAPPO ablation/control arms; the six
heuristics are already generated by full-MAPPO heldout evaluation.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import yaml

import fieldvision_scale_v10 as v10

N = 128
ROOT = v10.ROOT
VARIANTS = ('full', 'full_constrained', 'placement_only', 'fixed_edf_task',
            'fixed_network_tier', 'fixed_compute_tier', 'decentralized_critic',
            'no_class_metadata')
NEW = tuple(v for v in VARIANTS if v != 'full')
HEURISTICS = ('local_only', 'edge_only', 'cloud_only', 'edf',
              'network_aware_edf', 'critical_first')
LEARNERS = ('full', 'ippo', 'qmix')
METRICS = v10.METRICS
V8 = Path('run_orchestration_experiments.py')
CONSTRAINT_TUNE = Path('configs/mappo_h123_lr3_constrained_v8.yaml')
WEIGHTED_TUNE = v10.TUNING['full']
H3 = v10.H3_PLAN


def variant_name(label):
    if label not in VARIANTS:
        raise ValueError('Unknown experiment variant: '+label)
    return 'full' if label == 'full_constrained' else label


def tuning(label):
    return CONSTRAINT_TUNE if label == 'full_constrained' else WEIGHTED_TUNE


def training_dir(label):
    return ROOT / f'fleet{N}' / f'{label}_training'


def evaluation_dir(label, protocol):
    return ROOT / f'fleet{N}' / f'{label}_{protocol}_evaluation'


def smoke_dir(label):
    return ROOT / f'fleet{N}' / f'{label}_optimizer_smoke'


def check_config():
    p = v10.preflight(N)
    # Training data and source must still be compatible with the already
    # selected full MAPPO checkpoint. No accidental protocol fork.
    v10.verify_selection(N, 'full')
    v10.ensure(CONSTRAINT_TUNE.is_file(), 'Missing frozen constrained control tuning')
    v10.ensure(WEIGHTED_TUNE.is_file(), 'Missing frozen weighted tuning')
    return p


def verify_training(label):
    if label == 'full':
        return v10.verify_selection(N, 'full')
    t = training_dir(label)
    p = t / 'selected_model.json'
    v10.ensure(p.is_file(), f'Missing selected model: {p}')
    data = v10.read_json(p)
    checks = {
        'runner_sha256':v10.sha(V8),
        'environment_sha256':v10.sha(v10.ENV_SOURCE),
        'base_config_sha256':v10.sha(v10.config_path(N)),
        'tuning_config_sha256':v10.sha(tuning(label)),
    }
    for key, val in checks.items():
        v10.ensure(data.get(key) == val, f'{label}: training checkpoint hash mismatch: {key}')
    v10.ensure(data.get('policy_variant') == variant_name(label), 'Wrong trained policy variant')
    grid = {float(x) for x in yaml.safe_load(tuning(label).read_text())['grid']['learning_rates']}
    ran = data.get('grid_tested', [])
    v10.ensure(len(ran) == len(grid) and {float(x['learning_rate']) for x in ran} == grid,
               'Did not run every predeclared learning rate')
    lr = float(data['chosen_config']['learning_rate'])
    v10.ensure(lr in grid, 'Selected a learning rate outside the grid')
    seeds = data.get('selected_training_trials', [])
    v10.ensure(sorted(int(x['train_seed']) for x in seeds) == [11, 23, 37],
               'Missing selected training seed')
    for seed in seeds:
        v10.ensure(float(seed['learning_rate']) == lr, 'Inconsistent learning rate')
        v10.ensure((Path(seed['path'])/'best_validation_checkpoint.pt').is_file(),
                   'Missing checkpoint: '+str(seed['path']))
    v10.ensure((t/'validation_ranking.csv').is_file(), 'Missing LR validation ranking')
    return data


def smoke(label, device):
    v10.ensure(label in NEW, 'The full MAPPO smoke is already completed in v10')
    check_config()
    output = smoke_dir(label)
    if output.exists():
        v10.ensure(all((output/x).is_file() for x in
                      ('training_manifest.json','training_history.csv','best_validation_checkpoint.pt')),
                   'Incomplete smoke output must be inspected and archived: '+str(output))
        print('EXISTING_POLICY_SMOKE_VERIFIED:',output)
        return
    cmd = [sys.executable, V8, '--mode','mappo-train', '--variant',variant_name(label),
           '--config',v10.config_path(N),'--tuning-config',tuning(label),
           '--output-root',output,'--device',device,'--episodes',4,
           '--ppo-epochs',1,'--dropout',0.0,'--seed',11]
    log=ROOT/'logs'/f'fleet{N}_{label}_optimizer_smoke.log'
    v10.run_logged(cmd, log)
    v10.ensure(all((output/x).is_file() for x in
                   ('training_manifest.json','training_history.csv','best_validation_checkpoint.pt')),
               'Optimizer smoke did not produce expected checkpoint files')
    print('V12_ABLATION_SMOKE_PASS:',label, '(diagnostic only, not a science result)')


def train(label, device):
    v10.ensure(label in NEW, 'Full MAPPO training is already verified in v10')
    check_config()
    output=training_dir(label)
    if output.exists():
        verify_training(label)
        print('EXISTING_ABLATION_TRAINING_VERIFIED:',output)
        return
    v10.ensure((smoke_dir(label)/'best_validation_checkpoint.pt').is_file(),
               f'Run smoke {label} before training')
    cmd=[sys.executable,V8,'--mode','mappo-sweep','--variant',variant_name(label),
         '--config',v10.config_path(N),'--tuning-config',tuning(label),
         '--output-root',output,'--device',device]
    log=ROOT/'logs'/f'fleet{N}_{label}_train.log'
    elapsed=v10.run_logged(cmd,log)
    verify_training(label)
    rec=ROOT/f'fleet{N}'/f'{label}_training_runtime.json'
    if not rec.exists():
        v10.write_json_new(rec, {'seconds':elapsed,'log':str(log),'log_sha256':v10.sha(log),
                                'runner_sha256':v10.sha(V8),
                                'selected_model_sha256':v10.sha(output/'selected_model.json')})
    print('V12_ABLATION_TRAINING_VERIFIED:',output)


def verify_eval(label,protocol):
    if label == 'full':
        return v10.verify_eval(N,'full',protocol)
    model=verify_training(label)
    directory=evaluation_dir(label,protocol)
    p=directory/'heldout_summary.json'
    r=directory/'heldout_mappo_results.csv'
    c=directory/'heldout_policy_comparison.csv'
    v10.ensure(all(x.is_file() for x in (p,r,c)),f'Incomplete output at {directory}')
    report=v10.read_json(p)
    v10.ensure(report['selected_model']==model, 'Evaluation selected model mismatch')
    v10.ensure(report.get('policy_variant')==variant_name(label), 'Evaluation variant mismatch')
    v10.ensure(report.get('training_seed_count')==3, 'Evaluation missing training seeds')
    scope='H3_INDEPENDENT_MOBILITY_EVALUATION' if protocol=='independent' else 'H1_H2_HELDOUT_UNCALIBRATED_NETWORK_SENSITIVITY'
    v10.ensure(report.get('scope')==scope,'Wrong evaluation scope')
    if protocol=='independent':
        v10.ensure(report.get('external_evaluation_plan_sha256')==v10.sha(H3),
                   'Independent H3 plan changed')
    else:
        v10.ensure(report.get('external_evaluation_plan_sha256') is None,
                   'Nominal evaluation wrongly uses an external H3 plan')
    plan=yaml.safe_load((H3 if protocol=='independent' else tuning(label)).read_text())
    scenarios=plan['heldout_scenarios']
    seeds=plan['heldout']['seeds']
    expected={(x['name'],int(seed),train_seed) for x in scenarios for seed in seeds for train_seed in (11,23,37)}
    with r.open(newline='',encoding='utf-8') as f:
        rows=list(csv.DictReader(f))
    actual={(x['scenario'],int(x['seed']),int(x['training_seed'])) for x in rows}
    v10.ensure(len(rows)==len(expected) and actual==expected and report.get('sample_size')==len(rows),
               'Missing/duplicate held-out evaluation cells')
    with c.open(newline='',encoding='utf-8') as f:
        compared=list(csv.DictReader(f))
    learned='mappo' if variant_name(label)=='full' else variant_name(label)
    selected=[x for x in compared if x.get('policy')==learned]
    expected_pairs={(x['scenario'],int(x['seed']),int(x['training_seed'])) for x in rows}
    actual_pairs={(x['scenario'],int(x['seed']),int(x['training_seed'])) for x in selected}
    v10.ensure(len(selected)==len(rows) and actual_pairs==expected_pairs,
               'Heldout policy comparison lacks complete learned row coverage')
    return rows,report


def eval_policy(label,protocol,device):
    if label=='full':
        v10.do_eval(N,'full',protocol,device)
        return
    v10.preflight(N, seed41=(protocol=='independent'))
    verify_training(label)
    dest=evaluation_dir(label,protocol)
    if dest.exists():
        verify_eval(label,protocol)
        print('EXISTING_ABLATION_EVALUATION_VERIFIED:',dest)
        return
    cmd=[sys.executable,V8,'--mode','mappo-heldout',
         '--config',v10.config_path(N),'--tuning-config',tuning(label),
         '--sweep-root',training_dir(label),'--output-root',dest,'--device',device]
    if protocol=='independent':
        cmd+=['--evaluation-plan',H3]
    log=ROOT/'logs'/f'fleet{N}_{label}_{protocol}_eval.log'
    v10.run_logged(cmd,log)
    verify_eval(label,protocol)
    print('V12_ABLATION_EVALUATION_VERIFIED:',dest)


def available_heuristics(protocol):
    v10.verify_eval(N,'full',protocol)
    path=evaluation_dir('full',protocol)/'heldout_policy_comparison.csv'
    v10.ensure(path.is_file(), f'Missing existing heuristic comparison: {path}')
    with path.open(newline='',encoding='utf-8') as f:
        rows=list(csv.DictReader(f))
    plan=yaml.safe_load((H3 if protocol=='independent' else WEIGHTED_TUNE).read_text())
    expected={(s['name'],int(e)) for s in plan['heldout_scenarios'] for e in plan['heldout']['seeds']}
    grouped={}
    for name in HEURISTICS:
        sub=[r for r in rows if r['policy']==name]
        keys={(r['scenario'],int(r['seed'])) for r in sub}
        v10.ensure(len(sub)==len(expected) and keys==expected,
                   f'Heuristic {name} missing/duplicated matched scenario+seed inputs')
        grouped[name]=sub
    return grouped


def write_csv(path,rows,fields):
    path=Path(path)
    with path.open('x',encoding='utf-8',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=fields,extrasaction='ignore')
        writer.writeheader();writer.writerows(rows)


def make_heuristic_summary(protocol, output):
    # All six baselines are already present in full MAPPO's frozen heldout CSV.
    h=available_heuristics(protocol)
    rows=[]
    for name,values in h.items():
        r={'fleet_uavs':N,'protocol':protocol,'variant':name,
           'evaluation_episodes':len(values),'training_seed_count':0,
           'source_evaluation':'full_'+protocol+'_evaluation'}
        for metric in METRICS:
            arr=[float(x[metric]) for x in values if x.get(metric) not in (None,'')]
            r[metric]=sum(arr)/len(arr) if len(arr)==len(values) else None
        rows.append(r)
    write_csv(output/'heuristic_summary.csv',rows,
              ['fleet_uavs','protocol','variant','evaluation_episodes','training_seed_count',
               'source_evaluation',*METRICS])
    return rows


def report(protocol):
    v10.preflight(N,seed41=(protocol=='independent'))
    from run_orchestration_experiments import generate_research_report
    ts=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    out=ROOT/'reports'/f'h123_128_{protocol}_{ts}'
    # Reject existing but incomplete/changed evaluations rather than passing
    # apparently plausible CSV data into a research table.
    for label in VARIANTS:
        if evaluation_dir(label,protocol).exists():
            verify_eval(label,protocol)
    for label in ('ippo','qmix'):
        if evaluation_dir(label,protocol).exists():
            v10.verify_eval(N,label,protocol)
    # Frozen-v8 method computes matched bootstraps against both architecture
    # variants and heuristics. Missing arms are explicitly marked pending.
    summary, stats=generate_research_report(ROOT,out,[N],protocol)
    heuristic=make_heuristic_summary(protocol,out)
    extras=[];missing=[]
    for algo in ('ippo','qmix'):
        d=evaluation_dir(algo,protocol)
        if not d.exists():
            missing.append(algo)
            continue
        _rows, payload=v10.verify_eval(N,algo,protocol)
        extras.append({'fleet_uavs':N,'protocol':protocol,'variant':algo,
                       'evaluation_episodes':payload['sample_size'],
                       'training_seed_count':payload['training_seed_count'],
                       'selected_learning_rate':payload['selected_model']['chosen_config']['learning_rate'],
                       **{m:payload['summary'].get(m) for m in METRICS}})
    all_rows=list(summary)+extras+heuristic
    write_csv(out/'complete_128_policy_table.csv',all_rows,
              ['fleet_uavs','protocol','variant','evaluation_episodes','training_seed_count',
               'selected_learning_rate','overall_sla','critical_sla',
               'standard_sla','batch_sla','fairness'])
    # Assemble H1/H3 learner comparisons using precisely matched task,
    # evaluation and training seeds, not mean differences masquerading as CI.
    from run_learning_baselines_v9 import _bootstrap_matched_deltas
    learn_ci=[]
    if evaluation_dir('full',protocol).exists():
        full_raw,_=v10.verify_eval(N,'full',protocol)
        for other in ('ippo','qmix'):
            if not evaluation_dir(other,protocol).exists():
                continue
            other_raw,_=v10.verify_eval(N,other,protocol)
            for metric in METRICS:
                if any(row.get(metric) in ('',None) for row in (*full_raw,*other_raw)):
                    continue
                estimate=_bootstrap_matched_deltas(full_raw,other_raw,metric)
                learn_ci.append({'fleet_uavs':N,'protocol':protocol,
                                 'comparison':'full_minus_'+other,
                                 'metric':metric,**estimate})
    write_csv(out/'paired_learning_baselines.csv',learn_ci,
              ['fleet_uavs','protocol','comparison','metric',
               'mean_gain_pp','ci95_low_pp','ci95_high_pp',
               'bootstrap_resamples','scenario_count',
               'evaluation_seed_count_per_scenario','training_seed_count'])
    manifest={'fleet_uavs':N,'protocol':protocol,
              'architecture_cells_complete':len(summary),
              'architecture_cells_expected':len(VARIANTS),
              'learners_completed':3-len(missing),'learners_expected':3,
              'heuristics_completed':len(heuristic),'heuristics_expected':len(HEURISTICS),
              'missing_learners':missing,'v8_source_sha256':v10.sha(V8),
              'v9_source_sha256':v10.sha(v10.FROZEN_V9),
              'environment_sha256':v10.sha(v10.ENV_SOURCE),
              'base_config_sha256':v10.sha(v10.config_path(N)),
              'native_seed27_sha256':v10.sha(v10.trajectory(N,27)),
              'native_seed41_sha256':v10.sha(v10.trajectory(N,41)) if protocol=='independent' else None,
              'limitations':['Single native mobility capture per protocol',
                             'Analytical uncalibrated radio',
                             '4-64 reward-weight sensitivity is a separate protocol; do not merge',
                             'No field-measured UAV energy']}
    v10.write_json_new(out/'v12_128_matrix_manifest.json',manifest)
    print('V12_128_MATRIX_REPORT:', out)
    print(f'H2 arms={len(summary)}/{len(VARIANTS)} learning={3-len(missing)}/3 heuristics={len(heuristic)}/6')
    print('TABLE_READY:',out/'complete_128_policy_table.csv')
    print('HEURISTICS:',out/'heuristic_summary.csv')
    print('PAIRED_H2_HEURISTICS:',out/'paired_bootstrap.csv')
    print('PAIRED_LEARNERS:',out/'paired_learning_baselines.csv')
    return out



def feasibility():
    """Independent necessary-bound capacity audit at the 128-UAV training/val split."""
    check_config()
    out=ROOT/f'fleet{N}'/'feasibility_validation'
    if out.exists():
        files=('class_feasibility_ceiling.csv','individual_necessary_bounds.csv','audit_manifest.json')
        v10.ensure(all((out/f).is_file() for f in files),
                   'Partial feasibility audit must be inspected before rerun')
        manifest=v10.read_json(out/'audit_manifest.json')
        v10.ensure(manifest.get('base_config_sha256')==v10.sha(v10.config_path(N)) and
                   manifest.get('runner_sha256')==v10.sha(V8) and
                   manifest.get('tuning_config_sha256')==v10.sha(WEIGHTED_TUNE),
                   'Existing feasibility audit has incompatible provenance')
        print('EXISTING_128_FEASIBILITY_VERIFIED:',out)
        return
    cmd=[sys.executable,V8,'--mode','feasibility-audit',
         '--config',v10.config_path(N),'--tuning-config',WEIGHTED_TUNE,
         '--audit-split','validation','--output-root',out]
    log=ROOT/'logs'/f'fleet{N}_feasibility_validation.log'
    v10.run_logged(cmd,log)
    v10.ensure((out/'class_feasibility_ceiling.csv').is_file() and
               (out/'audit_manifest.json').is_file(), 'Feasibility audit incomplete')
    print('V12_128_NECESSARY_FEASIBILITY_PASS:',out)


def summary_status():
    for name in VARIANTS:
        try:
            verify_training(name)
            t='TRAIN_VERIFIED'
        except Exception as e:
            t='TRAIN_PENDING: '+str(e)[:95]
        print(f'{name:24} {t}')
        for protocol in ('nominal','independent'):
            try:
                verify_eval(name,protocol)
                s='VERIFIED'
            except Exception:
                s='PENDING'
            print(f'  {protocol}: {s}')
    for proto in ('nominal','independent'):
        try:
            have=available_heuristics(proto)
            print(f'HEURISTICS {proto}: VERIFIED {len(have)}/6 (reuse, no new execution)')
        except Exception as e:
            print(f'HEURISTICS {proto}: PENDING ({str(e)[:100]})')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('status','heuristics','feasibility','smoke','train','eval','report','all-nominal','all-h3'))
    parser.add_argument('variant',nargs='?',choices=NEW)
    parser.add_argument('--protocol',choices=('nominal','independent'),default='nominal')
    parser.add_argument('--device',choices=('cpu','cuda'),default=os.getenv('NOMS_DEVICE','cpu'))
    args=parser.parse_args()
    if args.action=='status':summary_status();return
    if args.action=='heuristics':
        v10.preflight(N,seed41=(args.protocol=='independent'))
        group=available_heuristics(args.protocol)
        print(f'HEURISTICS_VERIFIED: {len(group)}; already computed with full MAPPO heldout, no rerun')
        for name,rows in group.items():
            print(name,'overall=',round(sum(float(x['overall_sla']) for x in rows)/len(rows),6),
                  'critical=',round(sum(float(x['critical_sla']) for x in rows)/len(rows),6))
        return
    if args.action=='report':report(args.protocol);return
    if args.action=='feasibility':feasibility();return
    if args.action in ('smoke','train','eval'):
        parser.error('Specify one missing MAPPO variant') if args.variant is None else None
        if args.action=='smoke':smoke(args.variant,args.device)
        if args.action=='train':train(args.variant,args.device)
        if args.action=='eval':eval_policy(args.variant,args.protocol,args.device)
        return
    if args.action in ('all-nominal','all-h3'):
        protocol='nominal' if args.action=='all-nominal' else 'independent'
        # Never start H3 without a valid, independently captured seed41 trace.
        v10.preflight(N,seed41=(protocol=='independent'))
        for variant in NEW:
            smoke(variant,args.device)
            train(variant,args.device)
            eval_policy(variant,protocol,args.device)
        report(protocol)


if __name__=='__main__':
    try:main()
    except (FileNotFoundError,ValueError,RuntimeError,KeyError,FileExistsError) as exc:
        print('V12_GATE_FAILED:',exc,file=sys.stderr)
        sys.exit(1)
